// Builds the Dutch page (nl/index.html) from the English page (index.html) and
// the translations in i18n/nl.json. Runs automatically before `dev` and `build`.
//
// Edit index.html and i18n/nl.json, never nl/index.html: it is overwritten.
// Text without a translation is listed as a warning, so nothing English slips through.
import fs from 'node:fs'
import path from 'node:path'
import { JSDOM } from 'jsdom'

const root = path.resolve(import.meta.dirname, '..')
const source = fs.readFileSync(path.join(root, 'index.html'), 'utf8')
const { _keep: keep = [], _comment, ...translations } = JSON.parse(fs.readFileSync(path.join(root, 'i18n/nl.json'), 'utf8'))
void _comment

const dom = new JSDOM(source)
const doc = dom.window.document
const missing = new Set()

const collapse = (text) => text.replace(/\s+/g, ' ').trim()
const needsTranslation = (text) => /[A-Za-z]/.test(text) && !keep.includes(text)

function translate(text) {
  const key = collapse(text)
  if (!needsTranslation(key)) return text
  if (!(key in translations)) {
    missing.add(key)
    return text
  }
  // Keep the surrounding whitespace so the markup layout stays the same.
  const lead = text.match(/^\s*/)[0]
  const trail = text.match(/\s*$/)[0]
  return lead + translations[key] + trail
}

// Text nodes (skipping scripts, styles and inline SVG)
function walk(node) {
  for (const child of node.childNodes) {
    if (child.nodeType === 3) child.textContent = translate(child.textContent)
    else if (child.nodeType === 1 && !['SCRIPT', 'STYLE', 'svg'].includes(child.tagName)) walk(child)
  }
}
walk(doc.head)
walk(doc.body)

// Attributes that people or screen readers see
for (const el of doc.querySelectorAll('[aria-label], [alt], meta[name="description"], meta[property^="og:"]')) {
  for (const attr of ['aria-label', 'alt', 'content']) {
    const value = el.getAttribute(attr)
    if (value) el.setAttribute(attr, translate(value))
  }
}

// Page language and the language switch
doc.documentElement.lang = 'nl'
for (const link of doc.querySelectorAll('[data-lang]')) {
  if (link.dataset.lang === 'nl') link.setAttribute('aria-current', 'page')
  else link.removeAttribute('aria-current')
}

const header = '<!-- Generated by scripts/build-nl.mjs from index.html and i18n/nl.json. Do not edit. -->\n'
fs.mkdirSync(path.join(root, 'nl'), { recursive: true })
fs.writeFileSync(path.join(root, 'nl/index.html'), dom.serialize().replace(/^<!DOCTYPE html>/i, '<!doctype html>\n' + header))

if (missing.size) {
  console.warn(`nl/index.html built, but ${missing.size} text(s) have no Dutch translation in i18n/nl.json:`)
  for (const text of missing) console.warn(`  - ${text}`)
} else {
  console.log('nl/index.html built, all text translated.')
}
