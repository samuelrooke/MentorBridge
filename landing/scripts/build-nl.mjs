// Builds the Dutch pages (nl/...) from the English pages and the translations in
// i18n/nl.json. Runs automatically before `dev` and `build`, or with `npm run i18n -w landing`.
//
// Edit the English pages, the partials and i18n/nl.json, never the files in nl/: they are overwritten.
// Text without a translation is listed as a warning, so nothing English slips through.
import fs from 'node:fs'
import path from 'node:path'
import { JSDOM } from 'jsdom'
import { PAGES, SITE_URL, compose, root } from './pages.mjs'

const { _keep: keep = [], _comment, ...translations } = JSON.parse(fs.readFileSync(path.join(root, 'i18n/nl.json'), 'utf8'))
void _comment

const missing = new Set()
const used = new Set()
const collapse = (text) => text.replace(/\s+/g, ' ').trim()
const needsTranslation = (text) => /[A-Za-z]/.test(text) && !keep.includes(text)

function translate(text) {
  const key = collapse(text)
  if (!needsTranslation(key)) return text
  if (!(key in translations)) {
    missing.add(key)
    return text
  }
  used.add(key)
  // Keep the surrounding whitespace so the markup layout stays the same.
  const lead = text.match(/^\s*/)[0]
  const trail = text.match(/\s*$/)[0]
  return lead + translations[key] + trail
}

// Text nodes (skipping scripts, styles and inline SVG)
function walk(node) {
  for (const child of node.childNodes) {
    if (child.nodeType === 3) child.textContent = translate(child.textContent)
    else if (child.nodeType === 1 && !['SCRIPT', 'STYLE', 'svg'].includes(child.tagName)) walk(child)
  }
}

for (const page of PAGES) {
  const source = compose(fs.readFileSync(path.join(root, page.file), 'utf8'), page)
  const dom = new JSDOM(source)
  const doc = dom.window.document

  walk(doc.head)
  walk(doc.body)

  // Attributes that people or screen readers see. Of the Open Graph tags only the texts are translated;
  // URLs, locales and the image are set below.
  const textMeta = 'meta[name="description"], meta[property="og:title"], meta[property="og:description"], meta[property="og:image:alt"]'
  for (const el of doc.querySelectorAll(`[aria-label], [alt], ${textMeta}`)) {
    for (const attr of ['aria-label', 'alt', 'content']) {
      const value = el.getAttribute(attr)
      if (value) el.setAttribute(attr, translate(value))
    }
  }

  // Links to other pages stay in Dutch: /students/ becomes /nl/students/. The language switch is left alone.
  for (const link of doc.querySelectorAll('a[href^="/"]:not([data-lang])')) {
    const href = link.getAttribute('href')
    if (!href.startsWith('//') && !href.startsWith('/nl/')) link.setAttribute('href', `/nl${href}`)
  }

  // Dutch addresses and locale. hreflang stays the same three links as on the English page.
  const setContent = (selector, value) => doc.querySelector(selector)?.setAttribute(selector.startsWith('link') ? 'href' : 'content', value)
  setContent('link[rel="canonical"]', `${SITE_URL}/nl${page.path}`)
  setContent('meta[property="og:url"]', `${SITE_URL}/nl${page.path}`)
  setContent('meta[property="og:image"]', `${SITE_URL}/og/og-nl.jpg`)
  setContent('meta[property="og:locale"]', 'nl_NL')
  setContent('meta[property="og:locale:alternate"]', 'en_US')

  // Page language and the language switch
  doc.documentElement.lang = 'nl'
  for (const link of doc.querySelectorAll('[data-lang]')) {
    if (link.dataset.lang === 'nl') link.setAttribute('aria-current', 'page')
    else link.removeAttribute('aria-current')
  }

  const header = `<!-- Generated by scripts/build-nl.mjs from ${page.file} and i18n/nl.json. Do not edit. -->\n`
  const out = path.join(root, 'nl', page.file)
  fs.mkdirSync(path.dirname(out), { recursive: true })
  fs.writeFileSync(out, dom.serialize().replace(/^<!DOCTYPE html>/i, '<!doctype html>\n' + header))
}

if (missing.size) {
  console.warn(`Dutch pages built, but ${missing.size} text(s) have no Dutch translation in i18n/nl.json:`)
  for (const text of missing) console.warn(`  - ${text}`)
} else {
  console.log(`Dutch pages built (${PAGES.length}), all text translated.`)
}

// Texts set from JavaScript are translated in src/main.js, so every entry here should be used by a page.
const unused = Object.keys(translations).filter((key) => !used.has(key))
if (unused.length) {
  console.warn(`${unused.length} translation(s) in i18n/nl.json are no longer used on any page:`)
  for (const text of unused) console.warn(`  - ${text}`)
}
